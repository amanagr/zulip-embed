// Build the /reference/api section of the docs site from TypeDoc output.
//
// TypeDoc (with typedoc-plugin-markdown) emits plain markdown whose
// first line is a heading like `# Class: ZulipClient`. Starlight's
// content collection wants YAML frontmatter with at least a `title`,
// so we post-process every emitted file: strip the leading heading,
// promote it to `title:`, and write the file back in place.
//
// Also writes a parent `index.md` so the reference section has a
// clickable landing page in the sidebar.
//
// Runs twice: once to invoke TypeDoc, once to walk the output.
// Called from `pnpm build:site` via npm scripts.

import {spawnSync} from "node:child_process";
import {readFileSync, readdirSync, rmSync, statSync, writeFileSync} from "node:fs";
import {dirname, join, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const outDir = resolve(root, "site-src/src/content/docs/reference/api");

// 1. Regenerate.
rmSync(outDir, {recursive: true, force: true});
const typedoc = spawnSync("npx", ["typedoc"], {cwd: root, stdio: "inherit"});
if (typedoc.status !== 0) {
    process.exit(typedoc.status ?? 1);
}

// 2. Walk the output and rewrite each .md into Starlight-frontmatter
// form. The first `# ...` line of each file becomes the `title`.
const HEADING = /^#\s+(?:(?:Class|Interface|Function|Type Alias|Enumeration|Variable|Module):\s+)?(.+?)\s*$/;

function walk(dir) {
    for (const name of readdirSync(dir)) {
        const path = join(dir, name);
        const stat = statSync(path);
        if (stat.isDirectory()) {
            walk(path);
            continue;
        }
        if (!path.endsWith(".md")) continue;
        rewrite(path);
    }
}

function rewrite(path) {
    const source = readFileSync(path, "utf8");
    const lines = source.split("\n");

    let firstHeadingIdx = -1;
    for (let i = 0; i < lines.length; i += 1) {
        const line = lines[i];
        if (line.trim() === "") continue;
        if (line.startsWith("# ")) {
            firstHeadingIdx = i;
        }
        break;
    }

    let title;
    let body;
    if (firstHeadingIdx >= 0) {
        const match = HEADING.exec(lines[firstHeadingIdx]);
        title = match ? match[1] : path;
        body = lines.slice(firstHeadingIdx + 1).join("\n").replace(/^\n+/, "");
    } else {
        // index.md from typedoc-plugin-markdown has no leading heading
        // in some templates — derive from file name.
        title = path.endsWith("index.md") ? "API reference" : path;
        body = source;
    }

    body = rewriteMarkdownLinks(body);

    // JSON-encode the title to escape any special YAML characters.
    const frontmatter = [
        "---",
        `title: ${JSON.stringify(title)}`,
        "editUrl: false",
        "---",
        "",
    ].join("\n");

    writeFileSync(path, frontmatter + body);
}

// TypeDoc emits intra-doc links like `[Channel](../interfaces/Channel.md)`.
// Starlight serves those pages at `/reference/api/interfaces/channel/`
// (lowercased, no `.md`). Rewrite the href so it matches the slug the
// site serves — unlowercased `.md` links 404 on Pages.
function rewriteMarkdownLinks(body) {
    return body.replace(/(\]\()([^)]+?)(\))/g, (match, open, href, close) => {
        if (/^(?:https?:|mailto:|tel:|#)/.test(href)) return match;
        const hashIdx = href.indexOf("#");
        const [urlPart, hashPart] = hashIdx >= 0 ? [href.slice(0, hashIdx), href.slice(hashIdx)] : [href, ""];
        if (!urlPart.endsWith(".md")) return match;
        const segments = urlPart.slice(0, -".md".length).split("/");
        const last = segments.pop() ?? "";
        const dir = segments.join("/");
        const prefix = dir === "" ? "" : `${dir}/`;
        return `${open}${prefix}${last.toLowerCase()}/${hashPart.toLowerCase()}${close}`;
    });
}

walk(outDir);

// 3. Overwrite the top-level index.md with a hand-written landing
// page that frames the reference section, keeping the autogenerated
// index just below the fold.
const originalIndex = readFileSync(join(outDir, "index.md"), "utf8");
const indexBody = originalIndex.replace(/^---\n[\s\S]*?\n---\n\n?/, "");
const indexFrontmatter = [
    "---",
    'title: "API reference"',
    'description: "Generated reference for every class, interface, and type exported from zulip-embed."',
    "editUrl: false",
    "---",
    "",
    "The SDK surface is generated directly from the `src/index.ts` barrel",
    "using [TypeDoc](https://typedoc.org/). If a symbol isn't listed here,",
    "it isn't part of the public API — it may change without a major",
    "version bump.",
    "",
    "For hand-written guides see [Events](/reference/events/),",
    "[Theming](/reference/theming/), and [Agents & AI](/reference/agents/).",
    "",
].join("\n");
writeFileSync(join(outDir, "index.md"), indexFrontmatter + indexBody);

console.log("API reference ready at", outDir);
